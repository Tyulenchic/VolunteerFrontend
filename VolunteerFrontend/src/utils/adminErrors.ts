/** Internal status names → words, for any backend text that no rule above covers. */
const WORDS: [RegExp, string][] = [
  [/\bAttendanceConfirmed\b/g, 'присутствие подтверждено'],
  [/\bDraft\b/g, 'черновик'],
  [/\bPublished\b/g, 'опубликовано'],
  [/\bCancelled\b/g, 'отменено'],
  [/\bCompleted\b/g, 'завершено'],
  [/\bArchived\b/g, 'в архиве'],
  [/\bPending\b/g, 'ожидает решения'],
  [/\bApproved\b/g, 'одобрено'],
  [/\bRejected\b/g, 'отклонено'],
];

const plain = (text: string) => WORDS.reduce((t, [re, w]) => t.replace(re, w), text);

/** True for a refusal by a business rule (the request was understood, but the action is not allowed now). */
export function isBusinessRuleError(err: unknown): boolean {
  const s = axios.isAxiosError(err) ? err.response?.status : undefined;
  return s === 400 || s === 409 || s === 403 || s === 404;
}

/**
 * User-facing text for a failed admin action.
 *  - business rule (400/409) → plain-language explanation of the rule;
 *  - 403 / 404 → short explanation;
 *  - network / timeout / 5xx → the shared safe messages from mapApiError;
 *  - anything unrecognised → `fallback` ("Не удалось …").
 */
export function adminErrorMessage(err: unknown, fallback: string): string {
  if (!axios.isAxiosError(err)) return fallback;
  const status = err.response?.status;
  if (status === 401) return 'Сессия истекла. Войдите в систему заново.';
  if (status === 403) return 'У вас нет прав на это действие.';
  if (status === 404) return 'Запись не найдена — возможно, её уже удалили. Обновите страницу.';

  const text = mapApiError(err);
  if (status !== 400 && status !== 409 && status !== 422) return text === 'Произошла ошибка. Попробуйте ещё раз.' ? fallback : text;

  for (const [re, friendly] of RULES) if (re.test(text)) return friendly;
  if (text === 'Произошла ошибка. Попробуйте ещё раз.') return fallback;
  return plain(text);
}
